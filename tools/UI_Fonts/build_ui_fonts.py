#!/usr/bin/env python3
"""Build the chooser's anti-aliased fonts into ui_fonts.h / ui_fonts.cpp.

The chooser (playlist_ui.cpp) uses the two typefaces of the Claude Design
mock (artifact "MP3 player UI prototype"): Lora Italic for playlist and
track names, DM Sans for the small footer. The mock is drawn on a 128 px
canvas, the panel is 240 px, so every size here is the mock's CSS size
times 240 / 128 = 1.875.

  UI_FONT_TITLE    Lora SemiBold Italic 22.5 px  playlist name     (12 px in the mock)
  UI_FONT_ROW_SEL  Lora SemiBold Italic 20.6 px  selected track    (11 px)
  UI_FONT_ROW      Lora Italic 16.9 px           the other tracks  (11 px scaled 0.82)
  UI_FONT_FOOT     DM Sans SemiBold 11.25 px     footer, +0.04 em letter spacing (6 px)

Glyphs are 4 bits per pixel (16 alpha levels), printable ASCII 0x20-0x7E,
plus the ellipsis U+2026 stored as code 0x7F. Anything else draws as '?'.

The fonts in fonts/ are the Google Fonts latin subsets that the mock itself
embeds. Both are variable fonts; they are instanced at the weights above
before rendering. Lora and DM Sans are under the SIL Open Font License 1.1
(fonts/OFL-Lora.txt, fonts/OFL-DMSans.txt), which allows embedding them in
firmware.

Usage (from this folder, --out is the flat sketch folder):
  pip install pillow fonttools brotli
  python build_ui_fonts.py --out ../../Stardance
"""

import argparse
import io
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SCALE = 240.0 / 128.0

# name, file, axis values, CSS px size in the mock, extra letter spacing (em)
FONTS = [
    ("UI_FONT_TITLE",   "Lora-Italic-latin.woff2", {"wght": 600},              12.0,        0.0),
    ("UI_FONT_ROW_SEL", "Lora-Italic-latin.woff2", {"wght": 600},              11.0,        0.0),
    ("UI_FONT_ROW",     "Lora-Italic-latin.woff2", {"wght": 400},              11.0 * 0.82, 0.0),
    ("UI_FONT_FOOT",    "DMSans-latin.woff2",      {"wght": 600, "opsz": 9},   6.0,         0.04),
]

FIRST, LAST = 0x20, 0x7F          # 0x7F holds the ellipsis
ELLIPSIS = "…"


def instance(path: Path, axes: dict) -> io.BytesIO:
    font = TTFont(str(path))
    if "fvar" in font:
        font = instancer.instantiateVariableFont(font, axes)
    font.flavor = None               # woff2 -> plain sfnt for FreeType
    buf = io.BytesIO()
    font.save(buf)
    buf.seek(0)
    return buf


def render_font(name, file, axes, css_px, tracking_em):
    px = css_px * SCALE
    data = instance(HERE / "fonts" / file, axes)
    font = ImageFont.truetype(data, size=px, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    track = tracking_em * px

    glyphs, bitmap = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = ELLIPSIS if code == 0x7F else chr(code)
        adv = font.getlength(ch) + track

        # Draw at a known baseline origin with room on every side, then crop.
        pad = int(px * 2)
        img = Image.new("L", (pad * 3, pad * 3), 0)
        ox, oy = pad, pad * 2
        ImageDraw.Draw(img).text((ox, oy), ch, font=font, fill=255, anchor="ls")
        bbox = img.getbbox()
        if bbox is None:
            glyphs.append((len(bitmap), 0, 0, 0, 0, round(adv * 16)))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        crop = img.crop(bbox)
        px4 = [min(15, (v * 15 + 127) // 255) for v in crop.tobytes()]
        offset = len(bitmap)
        for row in range(h):            # two pixels per byte, high nibble first, rows padded
            line = px4[row * w:(row + 1) * w]
            if len(line) % 2:
                line = line + [0]
            for i in range(0, len(line), 2):
                bitmap.append((line[i] << 4) | line[i + 1])
        glyphs.append((offset, w, h, x0 - ox, y0 - oy, round(adv * 16)))

    return {
        "name": name, "px": px, "ascent": ascent, "descent": descent,
        "glyphs": glyphs, "bitmap": bitmap, "desc": f"{file} {axes} {px:.2f} px",
    }


def c_bytes(data, per_line=20):
    lines = []
    for i in range(0, len(data), per_line):
        lines.append("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + per_line]) + ",")
    return "\n".join(lines) if lines else "  0x00,"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="sketch folder (flat), e.g. ../../Stardance")
    args = ap.parse_args()
    out = Path(args.out)

    fonts = [render_font(*f) for f in FONTS]

    h = [
        "#pragma once",
        "#include <stdint.h>",
        "",
        "// GENERATED by tools/UI_Fonts/build_ui_fonts.py - do not hand-edit.",
        "// Regenerate with: python build_ui_fonts.py --out <sketch folder>",
        "//",
        "// Anti-aliased chooser fonts, 4 bits per pixel. Codes 0x20-0x7E are ASCII,",
        "// 0x7F is the ellipsis. Lora and DM Sans, SIL Open Font License 1.1.",
        "",
        "struct UiGlyph {",
        "  uint16_t offset;   // into UiFont::bitmap",
        "  uint8_t  w, h;     // bitmap size; rows are padded to whole bytes",
        "  int8_t   dx, dy;   // top-left of the bitmap relative to the pen on the baseline",
        "  uint16_t adv16;    // advance in 1/16 px",
        "};",
        "",
        "struct UiFont {",
        "  const uint8_t *bitmap;",
        "  const UiGlyph *glyphs;   // UI_FONT_FIRST .. UI_FONT_LAST",
        "  uint8_t        ascent;   // px above the baseline",
        "  uint8_t        descent;  // px below it",
        "};",
        "",
        f"#define UI_FONT_FIRST 0x{FIRST:02X}",
        f"#define UI_FONT_LAST  0x{LAST:02X}",
        "#define UI_FONT_ELLIPSIS 0x7F",
        "",
    ]
    for f in fonts:
        h.append(f"extern const UiFont {f['name']};   // {f['desc']}")
    h.append("")

    c = [
        '#include "ui_fonts.h"',
        "",
        "// GENERATED by tools/UI_Fonts/build_ui_fonts.py - do not hand-edit.",
        "",
    ]
    total = 0
    for f in fonts:
        n = f["name"].lower()
        c.append(f"// {f['desc']}")
        c.append(f"static const uint8_t {n}_bitmap[] = {{")
        c.append(c_bytes(f["bitmap"]))
        c.append("};")
        c.append(f"static const UiGlyph {n}_glyphs[] = {{")
        for g in f["glyphs"]:
            c.append("  {{ {}, {}, {}, {}, {}, {} }},".format(*g))
        c.append("};")
        c.append(f"const UiFont {f['name']} = {{ {n}_bitmap, {n}_glyphs, {f['ascent']}, {f['descent']} }};")
        c.append("")
        size = len(f["bitmap"]) + len(f["glyphs"]) * 8
        total += size
        print(f"{f['name']:16s} {f['px']:6.2f} px  {size:6d} bytes")
    print(f"total {total} bytes of flash")

    (out / "ui_fonts.h").write_text("\n".join(h), encoding="utf-8")
    (out / "ui_fonts.cpp").write_text("\n".join(c), encoding="utf-8")
    print("wrote", out / "ui_fonts.h", "and", out / "ui_fonts.cpp")


if __name__ == "__main__":
    main()
